let ui = "tr";
export const setUiLang = (lang) => {
  ui = TEXT[lang] ? lang : "tr";
  document.documentElement.lang = ui;
};
export const uiLang = () => ui;
// A message, with $1, $2 … replaced by the arguments.
export const t = (key, ...subs) => String(TEXT[ui][key] ?? key).replace(/\$(\d)/g, (_, n) => subs[n - 1] ?? "");
export const posLabel = (pos) => pos.split("/").map((p) => TEXT[ui].pos[p] || p).join(" / ");
export const langName = (code) => LANGS[code]?.[ui] || code;
// A field written per native language ({ tr, en }), or a plain string.
export const pick = (value, native) => (value && typeof value === "object" ? value[native] ?? value.tr ?? "" : value ?? "");
